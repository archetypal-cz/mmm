#!/usr/bin/env python3
"""Extract static game vocabulary from the (prep-processed) Fortran sources
into web/data.js, so the UI uses exactly the game's own words.

  ITEM_WORDS   MMSB  DATA CTEM1/ctem2   149 nouns the parser knows (1..107 = IVEN items)
  ITEM_SHOWN   MMM   MMRI FORMATs       how the game lists items 1..53 ("rezavou lopatku")
  SCENERY      wasm/scenery.json         room -> nouns the verb handlers accept there
                                         although IVEN does not place them (gate, doors...)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "native" / "build"


def read(name):
    return (BUILD / name).read_bytes().decode("cp852")


def statement(text, start_re):
    """Join a (continued) fixed-form statement starting at start_re."""
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if re.match(start_re, line, re.I):
            body = [line[6:72]]
            for nxt in lines[i + 1:]:
                if len(nxt) > 5 and nxt[0] not in "Cc*" and nxt[5] not in " 0":
                    body.append(nxt[6:72].ljust(66))
                else:
                    break
            return "".join(body)
    raise SystemExit(f"not found: {start_re}")


def quoted(stmt):
    return [m.replace("''", "'") for m in re.findall(r"'((?:[^']|'')*)'", stmt)]


mmsb = read("MMSB.FOR")
words = quoted(statement(mmsb, r"\s+DATA CTEM1/")) + quoted(statement(mmsb, r"\s+data ctem2/"))
assert len(words) == 149, len(words)

mmm = read("MMM.FOR")
shown, label_of = {}, {}
lines = mmm.split("\n")
for i, line in enumerate(lines):
    m = re.match(r"\s*(\d*)\s+F='\(''(.*)''\$\)'", line)
    if m and i + 1 < len(lines):
        n = re.search(r"IF\(J\.EQ\.(\d+)\)WRITE", lines[i + 1])
        if n:
            shown[int(n.group(1))] = m.group(2).replace("''''", "'").strip()
            label_of[int(n.group(1))] = m.group(1)

# the same item names in the new Czech translation (lang=cz), by FORMAT label
new = {r["label"]: r["new"] for r in json.loads(
    (ROOT / "wasm" / "cz" / "messages.json").read_text(encoding="utf-8")) if r["file"] == "MMM"}
shown_cz = {j: re.sub(r"\{[^}]*\}", "", new.get(label_of[j], "")).strip() or shown[j] for j in shown}

data = {
    "ITEM_WORDS": [w.strip() for w in words],
    "ITEM_SHOWN": [shown.get(i, "") for i in range(1, 54)],
    "ITEM_SHOWN_CZ": [shown_cz.get(i, "") for i in range(1, 54)],
    "SCENERY": {int(k): v for k, v in json.loads(
        (ROOT / "wasm" / "scenery.json").read_text(encoding="utf-8"))["rooms"].items()},
}
out = "// Generated by wasm/gen_data.py from the Fortran sources. Do not edit.\n"
for k, v in data.items():
    out += f"export const {k} = {json.dumps(v, ensure_ascii=False)};\n"
(ROOT / "wasm" / "web" / "data.js").write_text(out, encoding="utf-8", newline="\n")
print(f"web/data.js: {len(words)} words, {sum(1 for s in shown.values() if s)} item names")
