      do i = 1, n
          itemp(i) = ibuf(i)
      enddo

      do i = 1, n*2
          if( temp(i:i) .ge. 'a' .and. temp(i:i) .le. 'z' ) then
              temp(i:i) = char( ichar(temp(i:i)) - 32)
          endif
      enddo
      do i = 1, n
          ibuf(i) = itemp(i)
      enddo
      end
